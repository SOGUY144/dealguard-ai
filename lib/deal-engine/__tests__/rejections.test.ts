import { describe, expect, it } from "vitest";
import { pickedLetter, rejectedLetters, rejectedLevers } from "../rejections";

describe("rejectedLevers — ลูกค้าปฏิเสธทางเลือกไหนไปแล้ว", () => {
  it.each([
    ["ไม่ซื้อเพิ่มครับ", ["volume"]],
    ["สั่งเพิ่มไม่ได้นะ งบมีแค่นี้", ["volume"]],
    ["เอาแค่ 1000 พอ", ["volume"]],
    ["ไม่เอาของแถม", ["bundle"]],
    ["ไม่ต้องแถมครับ", ["bundle"]],
    ["ไม่จ่ายสดนะ ขอเครดิต", ["cash"]],
    ["โอนทันทีไม่ได้", ["cash"]],
    ["ไม่เอาสักอย่าง ขอ 125", ["volume", "cash", "bundle"]],
  ] as const)("%s → %j", (text, expected) => {
    expect(rejectedLevers([text])).toEqual(expected);
  });

  it("ข้อความต่อราคาปกติ / ตกลง ไม่นับเป็นการปฏิเสธ", () => {
    expect(rejectedLevers(["ขอ 125 ได้ไหม 1000 ชิ้น", "จ่ายสดลดได้ไหม", "เอาของแถมก็ได้", "ซื้อเพิ่มได้ราคาเท่าไหร่"])).toEqual([]);
  });

  // เทสสำนวนจริงของลูกค้า 24 ต.ค. 2569 — รอบแรกจับได้แค่ 14 จาก 41 สำนวน
  it.each([
    ["ซื้อเพิ่มไม่ไหว", "volume"], ["ร้านเล็ก ไม่อยากสั่งเยอะ", "volume"], ["1000 พอครับ", "volume"], ["แค่ 1000 ชิ้นพอ", "volume"],
    ["ไม่อยากสต๊อกเยอะ", "volume"], ["ไม่สั่งถึง 2000", "volume"], ["เอาเท่าเดิม 1000", "volume"], ["ไม่ต้องเพิ่มจำนวนครับ", "volume"],
    ["ของแถมไม่ต้อง", "bundle"], ["ไม่ต้องมีของแถม", "bundle"], ["ของแถมไม่เอา", "bundle"], ["ไม่ใช้ของแถม", "bundle"],
    ["ไม่ต้องให้ของแถม ลดราคาแทนได้ไหม", "bundle"], ["ของแถมไม่จำเป็น", "bundle"], ["ไม่เอาของแถม จ่ายสดได้", "bundle"],
    ["จ่ายสดไม่ไหว", "cash"], ["ไม่สะดวกจ่ายสด", "cash"], ["ขอ 30 วันเหมือนเดิม", "cash"], ["โอนทันทีไม่สะดวก", "cash"],
    ["ไม่มีเงินสด", "cash"], ["เงินสดไม่มีครับ", "cash"], ["ต้องใช้เครดิต", "cash"], ["ขอจ่ายทีหลัง", "cash"],
    ["ไม่จ่ายเงินสด", "cash"], ["จ่ายสดไม่ค่อยสะดวก", "cash"], ["ไม่ต้องจ่ายสดได้ไหม", "cash"],
    ["ไม่ชอบสักข้อ", "all"], ["ไม่โอเคทั้งหมดเลย", "all"], ["ไม่รับทั้งหมด", "all"], ["ไม่เอาทุกข้อ", "all"], ["ไม่ได้สักข้อ", "all"],
  ] as const)("สำนวนจริง: %s → %s", (text, lever) => {
    expect(rejectedLevers([text])).toEqual(lever === "all" ? ["volume", "cash", "bundle"] : [lever]);
  });

  it.each([
    "ไม่มีปัญหา จ่ายสดเลย", "จ่ายสดไม่มีปัญหาครับ", "ไม่มีของแถมหรอ", "ทำไมไม่แถมให้หน่อย", "จ่ายสดไม่ได้หรอ",
    "ถ้าซื้อเยอะไม่ลดหรอ", "ขอ 125 ส่งภายใน 3 วันได้ไหม", "ไม่ได้ครับ ขอ 125", "ไม่เป็นไรครับ เอาข้อ B", "โอนก่อนได้ครับ",
    "มีของแถมอะไรบ้าง", "เอา 1000 ชิ้น", "ไม่รู้ว่าจะเอาข้อไหนดี",
  ])("ไม่ใช่การปฏิเสธ (ถาม/ตกลง/อยากได้): %s", (text) => {
    expect(rejectedLevers([text])).toEqual([]);
  });

  it("รวมจากหลายข้อความ เรียงตาม ซื้อเพิ่ม / จ่ายสด / ของแถม", () => {
    expect(rejectedLevers(["ไม่เอาของแถม", "ไม่ซื้อเพิ่ม"])).toEqual(["volume", "bundle"]);
  });

  it.each([
    ["เอาข้อ B", "B"], ["ข้อ c ครับ", "C"], ["B ครับ", "B"], ["เลือก A", "A"], ["โอเคข้อ A เลย", "A"],
    ["ไม่เอาข้อ B", null], ["ขอ 125 ได้ไหม", null], ["ข้อไหนถูกสุด", null], ["Bluetooth มีไหม", null],
  ] as const)("พิมพ์เลือกข้อ: %s → %s", (text, letter) => {
    expect(pickedLetter(text)).toBe(letter);
  });

  it("ไม่เอาข้อ A / ไม่รับ C → ตัวอักษรที่ปฏิเสธ (ต้องเทียบกับการ์ดตอนนั้น)", () => {
    expect(rejectedLetters("ไม่เอาข้อ A")).toEqual(["A"]);
    expect(rejectedLetters("ไม่รับ C ครับ")).toEqual(["C"]);
    expect(rejectedLetters("เอาข้อ A")).toEqual([]);
  });
});
